from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from app.main import app
from app.services.fields import PAYMENT_FIELDS

ROOT = Path(__file__).parent.parent
OUTPUT = ROOT / "generated" / "frontend-types" / "index.ts"


def name(value: str) -> str:
    return re.sub(r"\W", "_", value)


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return name(schema["$ref"].split("/")[-1])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts(item) for item in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join("null" if value == "null" else ts({"type": value}) for value in kind)
    if kind == "array":
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts(extra)}>" if isinstance(extra, dict) else "Record<string, unknown>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def render(schema: dict[str, Any]) -> str:
    lines = ["// Generated by scripts/generate_types.py. Do not edit.", ""]
    for original, definition in schema["components"]["schemas"].items():
        type_name = name(original)
        if definition.get("type") == "object" and "properties" in definition:
            required = set(definition.get("required", []))
            lines.append(f"export interface {type_name} {{")
            for field, value in definition["properties"].items():
                lines.append(f"  {json.dumps(field, ensure_ascii=False)}{'' if field in required else '?'}: {ts(value)};")
            lines.append("}")
        else:
            lines.append(f"export type {type_name} = {ts(definition)};")
        lines.append("")
    field_ids = ", ".join(json.dumps(field.id) for field in PAYMENT_FIELDS)
    lines.append(f"export const PAYMENT_FIELD_IDS = [{field_ids}] as const;")
    lines.append("export type PaymentFieldId = typeof PAYMENT_FIELD_IDS[number];")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    schema = app.openapi()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(schema), encoding="utf-8")
    (OUTPUT.parent / "openapi.json").write_text(json.dumps(schema, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    print(f"Generated {(OUTPUT.parent / 'openapi.json').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
